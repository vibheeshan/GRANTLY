/**
 * ICS (iCalendar - RFC 5545) generation utility
 * Generates standards-compliant .ics files with VEVENT and VALARM at T-7 and T-1.
 * Escapes special characters in text fields (commas, semicolons, backslashes, newlines).
 */

/**
 * Escapes text according to RFC 5545 section 3.3.11
 * Commas, semicolons, and backslashes must be escaped with a backslash.
 * Newlines must be converted to \n
 */
export function escapeIcsText(text) {
  if (text === null || text === undefined) return "";
  return String(text)
    .replace(/\\/g, "\\\\")
    .replace(/;/g, "\\;")
    .replace(/,/g, "\\,")
    .replace(/\r\n/g, "\\n")
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\n");
}

/**
 * Format a Date or date string (YYYY-MM-DD) into iCalendar UTC or date-time string
 * Format: YYYYMMDDTHHmmssZ
 */
export function formatIcsDate(dateInput, isEnd = false) {
  if (!dateInput) {
    const now = new Date();
    return now.toISOString().replace(/[-:]/g, "").split(".")[0] + "Z";
  }

  const d = new Date(dateInput);
  if (isNaN(d.getTime())) {
    const fallback = new Date();
    return fallback.toISOString().replace(/[-:]/g, "").split(".")[0] + "Z";
  }

  // If input is YYYY-MM-DD, set deadline time to 23:59:00 UTC (or end of day)
  if (typeof dateInput === "string" && /^\d{4}-\d{2}-\d{2}$/.test(dateInput)) {
    const [y, m, day] = dateInput.split("-").map(Number);
    const dateObj = new Date(Date.UTC(y, m - 1, day, isEnd ? 23 : 9, isEnd ? 59 : 0, 0));
    return dateObj.toISOString().replace(/[-:]/g, "").split(".")[0] + "Z";
  }

  return d.toISOString().replace(/[-:]/g, "").split(".")[0] + "Z";
}

/**
 * Builds a single VEVENT string with VALARM at T-7 days and T-1 day
 */
export function buildIcsEvent({
  id = `event-${Date.now()}`,
  title = "Scholarship Deadline",
  description = "",
  provider = "",
  location = "Online Application Portal",
  deadline,
  url = "https://grantly.app",
  awardAmount = 0,
  currency = "INR"
}) {
  const dtStamp = formatIcsDate(new Date());
  const dtStart = formatIcsDate(deadline, false);
  const dtEnd = formatIcsDate(deadline, true);

  const cleanTitle = escapeIcsText(title);
  const cleanProvider = escapeIcsText(provider);
  const cleanLocation = escapeIcsText(location);
  const cleanUrl = escapeIcsText(url);

  const descFull = [
    cleanTitle,
    provider ? `Provider: ${cleanProvider}` : "",
    awardAmount ? `Award: ${currency} ${awardAmount}` : "",
    description ? `Details: ${escapeIcsText(description)}` : "",
    `Application URL: ${cleanUrl}`,
    "Generated by GRANTLY - Student Success Platform"
  ]
    .filter(Boolean)
    .join("\\n");

  return [
    "BEGIN:VEVENT",
    `UID:grantly-${id}@grantly.app`,
    `DTSTAMP:${dtStamp}`,
    `DTSTART:${dtStart}`,
    `DTEND:${dtEnd}`,
    `SUMMARY:Deadline: ${cleanTitle}`,
    `DESCRIPTION:${descFull}`,
    `LOCATION:${cleanLocation}`,
    `URL:${cleanUrl}`,
    "STATUS:CONFIRMED",
    // Reminder at T-7 days (7 days before deadline)
    "BEGIN:VALARM",
    "ACTION:DISPLAY",
    `DESCRIPTION:Reminder: 7 days until deadline for ${cleanTitle}`,
    "TRIGGER:-P7D",
    "END:VALARM",
    // Reminder at T-1 day (24 hours before deadline)
    "BEGIN:VALARM",
    "ACTION:DISPLAY",
    `DESCRIPTION:Urgent: 1 day until deadline for ${cleanTitle}!`,
    "TRIGGER:-P1D",
    "END:VALARM",
    "END:VEVENT"
  ].join("\r\n");
}

/**
 * Builds a full VCALENDAR document containing multiple scholarship deadlines
 */
export function buildAllDeadlinesIcs(scholarships = []) {
  const header = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//GRANTLY//Scholarship Tracker 2.0//EN",
    "CALSCALE:GREGORIAN",
    "METHOD:PUBLISH",
    "X-WR-CALNAME:Grantly Scholarship Deadlines",
    "X-WR-TIMEZONE:UTC",
    "X-WR-CALDESC:Comprehensive scholarship application deadlines and reminder alarms exported from GRANTLY."
  ].join("\r\n");

  const events = scholarships.map((sch) =>
    buildIcsEvent({
      id: sch.id,
      title: sch.title || sch.name,
      description: sch.description,
      provider: sch.provider,
      deadline: sch.deadline,
      url: sch.applicationUrl || "https://grantly.app",
      awardAmount: sch.awardAmount || sch.amount,
      currency: sch.currency || "INR"
    })
  );

  const footer = "END:VCALENDAR";

  return [header, ...events, footer].join("\r\n");
}

/**
 * Triggers browser download of an .ics file and returns timestamp
 */
export function downloadIcsFile(filename = "grantly-deadlines.ics", icsContent = "") {
  if (typeof window === "undefined") return null;

  const blob = new Blob([icsContent], { type: "text/calendar;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.setAttribute("download", filename.endsWith(".ics") ? filename : `${filename}.ics`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);

  const timestamp = new Date().toISOString();
  try {
    localStorage.setItem("grantly_last_calendar_export_v2", timestamp);
  } catch (e) {
    // Ignore storage errors
  }
  return timestamp;
}

/**
 * Gets the last calendar export timestamp
 */
export function getLastCalendarExportTime() {
  if (typeof window === "undefined") return null;
  try {
    return localStorage.getItem("grantly_last_calendar_export_v2") || null;
  } catch (e) {
    return null;
  }
}
